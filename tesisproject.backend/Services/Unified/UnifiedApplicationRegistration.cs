        services.AddScoped<IUnifiedCatalogRepository<ProductAttribute>, UnifiedCatalogRepository<ProductAttribute>>();
        services.AddScoped<IUnifiedCatalogRepository<ProductType>, UnifiedCatalogRepository<ProductType>>();
        services.AddScoped<IUnifiedCatalogRepository<ProjectExtensionType>, UnifiedCatalogRepository<ProjectExtensionType>>();
        services.AddScoped<IUnifiedCatalogRepository<ProjectOriginType>, UnifiedCatalogRepository<ProjectOriginType>>();
