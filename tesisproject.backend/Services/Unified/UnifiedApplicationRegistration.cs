/// <summary>Isolated opt-in composition. Does not activate MVC routes, seed data or open a database.</summary>
public static class UnifiedApplicationRegistration
{
    public static IServiceCollection AddUnifiedDide(this IServiceCollection services,
        IConfiguration configuration, Action<DbContextOptionsBuilder> configureDatabase)
    {
        ArgumentNullException.ThrowIfNull(configuration);
        ArgumentNullException.ThrowIfNull(configureDatabase);
        // Mixing Identity stores or registering this composition twice is a configuration error.
        if (services.Any(d => d.ServiceType == typeof(IUnifiedUnitOfWork)
            || d.ServiceType == typeof(IUserStore<IdentityUser<int>>)
            || d.ServiceType == typeof(UnifiedDideDbContext)))
            throw new InvalidOperationException("Unified DIDE requires an isolated service collection without another Identity store or Unified composition.");
        services.AddSingleton(configuration);
        services.AddLogging();
        services.AddMemoryCache();
        services.AddHttpContextAccessor();
        services.AddAuthentication();
        services.AddRouting();
        services.AddAuthorization();
        services.AddDbContext<UnifiedDideDbContext>(configureDatabase);
        services.AddScoped<IUnifiedUnitOfWork, UnifiedUnitOfWork>();
        services.AddScoped<IUnifiedArticleRegistrationMatrixRepository, UnifiedArticleRegistrationMatrixRepository>();
        services.AddScoped<IGenericRepository<RegistrationMatrixColumn>, UnifiedGenericRepository<RegistrationMatrixColumn>>();
        services.AddScoped<IGenericRepository<RegistrationMatrixRow>, UnifiedGenericRepository<RegistrationMatrixRow>>();
        services.AddScoped<IGenericRepository<RegistrationMatrixCell>, UnifiedGenericRepository<RegistrationMatrixCell>>();
