        services.AddScoped<IUnifiedRegistrationMatrixService, UnifiedRegistrationMatrixService>();
        services.AddScoped<IUnifiedArticleConfigurationRepository, UnifiedArticleConfigurationRepository>();
        services.AddScoped<IUnifiedArticleConfigurationService, UnifiedArticleConfigurationService>();
        services.AddScoped<IUnifiedArticleRegistrationRepository, UnifiedArticleRegistrationRepository>();
        services.AddScoped<IUnifiedArticleFormSelector, UnifiedArticleFormSelector>();
        services.AddScoped<IUnifiedArticleRegistrationCommandService, UnifiedArticleRegistrationCommandService>();
        services.AddScoped<ICurrentUserService, CurrentUserService>();
        services.AddScoped<ITokenService, JwtTokenService>();
        services.AddOptions<ExternalApiOptions>().Bind(configuration.GetSection(ExternalApiOptions.SectionName))
            .ValidateDataAnnotations().ValidateOnStart();
        services.AddOptions<StorageOptions>().Bind(configuration.GetSection(StorageOptions.SectionName))
            .Validate(o => !string.IsNullOrWhiteSpace(o.RootPath), "Storage:RootPath is required").ValidateOnStart();
        services.AddOptions<DocumentRecognitionOptions>().Bind(configuration.GetSection(DocumentRecognitionOptions.SectionName))
            .ValidateDataAnnotations().ValidateOnStart();
        services.AddHttpClient("ExternalApi").ConfigureHttpClient((sp, client) =>
        {
            var options = sp.GetRequiredService<IOptions<ExternalApiOptions>>().Value;
            client.BaseAddress = new Uri(options.BaseUrl);
            client.Timeout = TimeSpan.FromSeconds(options.TimeoutSeconds);
            if (!string.IsNullOrWhiteSpace(options.UserAgent))
                client.DefaultRequestHeaders.Add("User-Agent", options.UserAgent);
        });
        services.AddHttpClient<IExternalDirectoryClient, ExternalDirectoryClient>("ExternalApi");
        services.AddHttpClient<IExternalPeriodsClient, ExternalPeriodsClient>("ExternalApi");
        services.AddHttpClient<IExternalAcademicsService, ExternalAcademicsService>("ExternalApi");
        services.AddHttpClient<IExternalDistributivosService, ExternalDistributivosService>("ExternalApi");
        services.AddHttpClient<IUnifiedAcademicCatalogSnapshotClient, UnifiedAcademicCatalogSnapshotClient>("ExternalApi");
        services.AddScoped<IUnifiedFacultySynchronizationService, UnifiedFacultySynchronizationService>();
        services.AddScoped<IUnifiedAcademicTermSynchronizationService, UnifiedAcademicTermSynchronizationService>();
        services.AddScoped<UnifiedCatalogSynchronizationController>();
        services.AddScoped<IUnifiedFacultyQueryService, UnifiedFacultyQueryService>();
