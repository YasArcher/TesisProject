        services.AddScoped<IUnifiedAppUserRepository, UnifiedAppUserRepository>();
        services.AddScoped<IUnifiedAuthorRepository, UnifiedAuthorRepository>();
        services.AddScoped<IUnifiedBudgetRepository, UnifiedBudgetRepository>();
        services.AddScoped<IUnifiedConvocationRepository, UnifiedConvocationRepository>();
        services.AddScoped<IUnifiedDocumentRepository, UnifiedDocumentRepository>();
        services.AddScoped<IUnifiedExportFieldRepository, UnifiedExportFieldRepository>();
        services.AddScoped<IUnifiedExportTemplateColumnRepository, UnifiedExportTemplateColumnRepository>();
        services.AddScoped<IUnifiedExportTemplateRepository, UnifiedExportTemplateRepository>();
